-- StageHub: esquema privado, no publicado por la Data API. Idempotente.
BEGIN;
CREATE SCHEMA IF NOT EXISTS stagehub;
REVOKE ALL ON SCHEMA stagehub FROM PUBLIC, anon, authenticated;
create table if not exists stagehub.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  full_name text not null,
  password_hash text not null,
  role text not null check (role in ('admin','bodega','supervisor','tecnico','consulta')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);

create table if not exists stagehub.sessions (
  token_hash text primary key,
  user_id bigint not null references stagehub.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  expires_at timestamptz not null,
  ip text,
  user_agent text
);
create index if not exists idx_sessions_user on stagehub.sessions(user_id);

create table if not exists stagehub.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#5b8cff',
  tracking_mode text not null default 'individual' check (tracking_mode in ('individual','cantidad')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists stagehub.subcategories (
  id bigint generated by default as identity primary key,
  category_id bigint not null references stagehub.categories(id) on delete cascade,
  name text not null,
  tracking_mode text not null default 'individual' check (tracking_mode in ('individual','cantidad')),
  spec_template jsonb not null default '[]'::jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(category_id, name)
);

create table if not exists stagehub.items (
  id bigint generated by default as identity primary key,
  internal_code text not null unique,
  name text not null,
  category_id bigint not null references stagehub.categories(id) on delete restrict,
  subcategory_id bigint references stagehub.subcategories(id) on delete restrict,
  brand text, model text,
  tracking_mode text not null check (tracking_mode in ('individual','cantidad')),
  qty_total integer not null default 0 check (qty_total >= 0),
  qty_maintenance integer not null default 0 check (qty_maintenance >= 0),
  qty_out_of_service integer not null default 0 check (qty_out_of_service >= 0),
  min_stock integer not null default 0 check (min_stock >= 0),
  unit_seq integer not null default 0,
  location text,
  acquisition_date date,
  acquisition_price numeric(14,2) check (acquisition_price is null or acquisition_price >= 0),
  supplier text, photo text, description text, notes text,
  specs jsonb not null default '[]'::jsonb,
  accessories jsonb not null default '[]'::jsonb,
  created_by bigint references stagehub.users(id) on delete set null,
  updated_by bigint references stagehub.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  maintenance_note text,
  out_of_service_note text,
  check (qty_maintenance + qty_out_of_service <= qty_total)
);
create index if not exists idx_items_category on stagehub.items(category_id);
create index if not exists idx_items_subcategory on stagehub.items(subcategory_id);
create index if not exists idx_items_name on stagehub.items(name);

create table if not exists stagehub.units (
  id bigint generated by default as identity primary key,
  item_id bigint not null references stagehub.items(id) on delete cascade,
  unit_code text not null unique,
  serial_number text,
  qr_token text not null unique,
  status text not null default 'disponible' check (status in ('disponible','mantenimiento','fuera_de_servicio')),
  location text, notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unit_number integer check (unit_number is null or unit_number >= 1),
  status_note text,
  status_changed_at timestamptz,
  status_changed_by text
);
create index if not exists idx_units_item_status on stagehub.units(item_id, status);
create unique index if not exists uq_units_serial on stagehub.units(item_id, lower(serial_number)) where serial_number is not null;
create unique index if not exists uq_units_number on stagehub.units(item_id, unit_number) where unit_number is not null;

create or replace view stagehub.v_item_stock as
select i.id as item_id,
  case when i.tracking_mode = 'individual' then coalesce(u.total,0) else i.qty_total end as total,
  case when i.tracking_mode = 'individual' then coalesce(u.maint,0) else i.qty_maintenance end as maintenance,
  case when i.tracking_mode = 'individual' then coalesce(u.oos,0) else i.qty_out_of_service end as out_of_service,
  case when i.tracking_mode = 'individual' then coalesce(u.avail,0) else greatest(i.qty_total-i.qty_maintenance-i.qty_out_of_service,0) end as available
from stagehub.items i
left join (
  select item_id, count(*) as total,
    count(*) filter (where status='mantenimiento') as maint,
    count(*) filter (where status='fuera_de_servicio') as oos,
    count(*) filter (where status='disponible') as avail
  from stagehub.units group by item_id
) u on u.item_id=i.id;

create table if not exists stagehub.audit_log (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  user_id bigint references stagehub.users(id) on delete set null,
  username text,
  action text not null,
  entity text not null,
  entity_id bigint,
  summary text not null,
  details jsonb
);
create index if not exists idx_audit_entity on stagehub.audit_log(entity, entity_id);
create index if not exists idx_audit_ts on stagehub.audit_log(ts);

create table if not exists stagehub.stock_snapshots (
  day date primary key,
  total integer not null,
  available integer not null,
  maintenance integer not null,
  out_of_service integer not null
);
create table if not exists stagehub.settings (key text primary key, value text);
create table if not exists stagehub.counters (key text primary key, value bigint not null default 0);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_ci ON stagehub.users(lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_name_ci ON stagehub.categories(lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS uq_subcategories_name_ci ON stagehub.subcategories(category_id,lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS uq_items_code_ci ON stagehub.items(lower(internal_code));
